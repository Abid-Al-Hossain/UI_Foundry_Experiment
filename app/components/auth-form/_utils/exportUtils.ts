import type { AuthFormState } from "../types";

export type ExportPayload = { fileName: string; mimeType: "text/plain;charset=utf-8"; content: string };

export function buildExportPayload(state: AuthFormState, fileName = "auth-form") : ExportPayload {
  return { fileName: `${fileName || "auth-form"}.jsx`, mimeType: "text/plain;charset=utf-8", content: buildReactCode(state) };
}

export function buildReactCode(state: AuthFormState) {
  return [
    "import * as React from \"react\";",
    "",
    "const state = " + JSON.stringify(state, null, 2) + ";",
  "",
  "const systemFonts = [\"Arial, system-ui\",\"Consolas, \\\"Liberation Mono\\\", \\\"Courier New\\\", ui-monospace, monospace\",\"\\\"Courier New\\\", ui-monospace, monospace\",\"Georgia, ui-serif, serif\",\"Helvetica, Arial, system-ui\",\"Menlo, Monaco, Consolas, \\\"Liberation Mono\\\", ui-monospace, monospace\",\"Monaco, Menlo, Consolas, \\\"Liberation Mono\\\", ui-monospace, monospace\",\"Roboto, system-ui, -apple-system, Arial\",\"\\\"Segoe UI\\\", system-ui, -apple-system, Arial\",\"system-ui, -apple-system, Segoe UI, Roboto, Helvetica, Arial\",\"\\\"Times New Roman\\\", Times, ui-serif, serif\",\"ui-monospace, SFMono-Regular, Menlo, Monaco, Consolas, \\\"Liberation Mono\\\", \\\"Courier New\\\", monospace\",\"ui-sans-serif, system-ui, -apple-system, Segoe UI, Roboto, Helvetica, Arial\",\"ui-serif, Georgia, Cambria, \\\"Times New Roman\\\", Times, serif\"];",
  "function resolveFont(s) { return s.fontBucket === \"google\" ? '\"' + s.googleFontFamily + '\", sans-serif' : (systemFonts[s.systemFontIdx] || \"system-ui\"); }",
  "function buildShadow(s) { if (!s.shadowEnabled) return \"none\"; var hex = Math.round(s.shadowOpacity * 255).toString(16).padStart(2, \"0\"); return s.shadowX + \"px \" + s.shadowY + \"px \" + s.shadowBlur + \"px \" + s.shadowSpread + \"px \" + s.shadowColor + hex; }",
    "",
    "function getShellStyle(disabled) {",
    "  return {",
    "    width: state.width,",
    "    minHeight: state.height,",
    "    padding: state.padding,",
    "    display: \"grid\",",
    "    gap: state.gap,",
    "    borderRadius: state.radiusLinked ? state.radius : `${state.radiusTL}px ${state.radiusTR}px ${state.radiusBR}px ${state.radiusBL}px`,",
    "    border: state.borderWidth + \"px \" + state.borderStyle + \" \" + (disabled && state.disabledUseCustomColors ? state.disabledBorder : state.border),",
    "    boxShadow: buildShadow(state),",
    "    background: disabled && state.disabledUseCustomColors ? state.disabledBg : state.background,",
    "    color: disabled && state.disabledUseCustomColors ? state.disabledText : state.foreground,",
    "    fontFamily: resolveFont(state),",
    "    fontStyle: state.fontStyle,",
    "    textTransform: state.textTransform,",
    "    textDecoration: state.textDecoration,",
    "    letterSpacing: `${state.letterSpacing}${state.letterSpacingUnit}`,",
    "    lineHeight: state.lineHeight,",
    "    opacity: disabled ? state.disabledOpacity : 1,",
    "    cursor: disabled ? state.disabledCursor : undefined,",
    "    transition: \"all \" + state.transitionDuration + \"ms \" + state.transitionEasing,",
    "  };",
    "}",
    "",
    "export default function AuthFormComponent({ onSubmit, onSocialLogin }) {",
    "  const isLoading = state.previewState === \"loading\";",
    "  const forcedError = state.previewState === \"error\";",
    "  const isSuccess = state.previewState === \"success\";",
    "  const [passwordVisible, setPasswordVisible] = React.useState(false);",
    "  const [submitting, setSubmitting] = React.useState(false);",
    "  const [message, setMessage] = React.useState(\"\");",
    "  const [submissionError, setSubmissionError] = React.useState(false);",
    "  const isError = forcedError || submissionError;",
    "  const disabled = state.disabled || isLoading || submitting;",
    "  const includeName = (state.mode === \"sign-up\" || state.mode === \"invite\") && state.fieldCount >= 3;",
    "  const includePassword = state.mode !== \"reset-password\" && state.fieldCount >= 2;",
    "  const helperId = state.id + \"-helper\";",
    "  const messageId = state.id + \"-message\";",
    "  const inputStyle = { width: \"100%\", border: \"1px solid \" + (isError ? state.errorColor : state.border), borderRadius: Math.max(10, state.radius - 12), background: \"rgba(255,255,255,.08)\", color: state.foreground, padding: \"11px 13px\", outline: \"none\", transition: state.transitionDuration > 0 ? \"border-color 0.2s ease, box-shadow 0.2s ease\" : \"none\" };",
    "  const handleSubmit = async (event) => {",
    "    event.preventDefault();",
    "    const form = event.currentTarget;",
    "    if (!form.checkValidity()) { form.reportValidity(); setSubmissionError(true); setMessage(\"Complete the required fields with valid values.\"); return; }",
    "    const values = Object.fromEntries(new FormData(form).entries());",
    "    setSubmitting(true); setSubmissionError(false); setMessage(\"\");",
    "    try { if (onSubmit) await onSubmit(values); setMessage(onSubmit ? \"Authentication request completed.\" : \"Form is valid. Pass onSubmit to connect authentication.\"); }",
    "    catch (error) { setSubmissionError(true); setMessage(error instanceof Error ? error.message : \"Authentication failed.\"); }",
    "    finally { setSubmitting(false); }",
    "  };",
    "  const handleSocialLogin = async () => {",
    "    setSubmitting(true); setSubmissionError(false); setMessage(\"\");",
    "    try { if (onSocialLogin) await onSocialLogin(\"sso\"); setMessage(onSocialLogin ? \"SSO request completed.\" : \"Pass onSocialLogin to connect the SSO provider.\"); }",
    "    catch (error) { setSubmissionError(true); setMessage(error instanceof Error ? error.message : \"SSO failed.\"); }",
    "    finally { setSubmitting(false); }",
    "  };",
    "",
    "  return (",
    "    <form id={state.id} aria-label={state.ariaLabel} aria-describedby={helperId + \" \" + messageId} data-validation-mode={state.validationMode} onSubmit={handleSubmit} style={getShellStyle(disabled)}>",
    "      <header style={{ display: \"grid\", gap: 6 }}>",
    "        <span style={{ color: state.accent, fontSize: 12, fontWeight: 700, letterSpacing: \"0.16em\", textTransform: \"uppercase\" }}>{state.mode} form</span>",
    "        <h3 style={{ margin: 0, fontSize: state.titleSize, fontWeight: state.fontWeight }}>{state.title}</h3>",
    "        <p id={helperId} style={{ margin: 0, color: state.muted, fontSize: state.bodySize }}>{state.description}</p>",
    "      </header>",
    "",
    "      <div style={{ display: \"grid\", gap: Math.max(10, state.gap - 4) }}>",
    "        {includeName && (",
    "          <label style={{ display: \"grid\", gap: 6, fontSize: 13, fontWeight: 700 }}>",
    "            Name",
    "            <input name=\"name\" type=\"text\" autoComplete=\"name\" required disabled={disabled} placeholder=\"Alex Morgan\" style={inputStyle} />",
    "          </label>",
    "        )}",
    "        <label style={{ display: \"grid\", gap: 6, fontSize: 13, fontWeight: 700 }}>",
    "          Email",
    "          <input name=\"email\" type=\"email\" autoComplete=\"email\" required disabled={disabled} aria-invalid={isError} placeholder=\"alex@example.com\" style={inputStyle} />",
    "        </label>",
    "        {includePassword && (",
    "          <label style={{ display: \"grid\", gap: 6, fontSize: 13, fontWeight: 700 }}>",
    "            Password",
    "            <span style={{ position: \"relative\", display: \"block\" }}>",
    "              <input name=\"password\" type={passwordVisible ? \"text\" : \"password\"} autoComplete={state.mode === \"sign-up\" ? \"new-password\" : \"current-password\"} required disabled={disabled} aria-invalid={isError} placeholder=\"********\" style={{ ...inputStyle, paddingRight: state.revealPassword ? 72 : inputStyle.padding }} />",
    "              {state.revealPassword && <button type=\"button\" disabled={disabled} aria-pressed={passwordVisible} aria-label={passwordVisible ? \"Hide password\" : \"Show password\"} onClick={() => setPasswordVisible((visible) => !visible)} style={{ position: \"absolute\", right: 8, top: \"50%\", transform: \"translateY(-50%)\", border: 0, background: \"transparent\", color: state.accent, fontSize: 12, fontWeight: 700 }}>{passwordVisible ? \"Hide\" : \"Show\"}</button>}",
    "            </span>",
    "          </label>",
    "        )}",
    "      </div>",
    "",
    "      {state.rememberMe && (",
    "        <label style={{ display: \"flex\", alignItems: \"center\", gap: 8, color: state.muted, fontSize: 13 }}>",
    "          <input name=\"remember\" type=\"checkbox\" disabled={disabled} defaultChecked />",
    "          Remember this device",
    "        </label>",
    "      )}",
    "",
    "      <button type=\"submit\" disabled={disabled} aria-busy={isLoading || submitting} style={{ border: 0, borderRadius: Math.max(12, state.radius - 8), background: state.accent, color: state.background, cursor: disabled ? state.disabledCursor : \"pointer\", fontWeight: 800, padding: \"12px 16px\", transition: state.transitionDuration > 0 ? \"opacity 0.2s ease, background 0.2s ease\" : \"none\" }}>",
    "        {isLoading || submitting ? \"Submitting...\" : state.label}",
    "      </button>",
    "",
    "      {state.showSocialLogin && <button type=\"button\" disabled={disabled} onClick={handleSocialLogin} style={{ border: state.borderWidth + \"px \" + state.borderStyle + \" \" + (state.disabled && state.disabledUseCustomColors ? state.disabledBorder : state.border), borderRadius: Math.max(12, state.radius - 8), background: \"transparent\", color: state.foreground, padding: \"11px 16px\", fontWeight: 700 }}>Continue with SSO</button>}",
    "",
    "      <p id={messageId} role={isError ? \"alert\" : \"status\"} style={{ margin: 0, color: isError ? \"#fca5a5\" : isSuccess ? \"#86efac\" : state.muted, fontSize: 13 }}>",
    "        {isError ? message || \"Check your email and password before submitting.\" : isSuccess ? \"Success. Your credentials are ready to submit.\" : message || state.helper}",
    "      </p>",
    "    </form>",
    "  );",
    "}",
    "",
  ].join("\n");
}
