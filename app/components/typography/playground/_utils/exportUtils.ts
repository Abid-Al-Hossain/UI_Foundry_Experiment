import {
  type TypographyState,
  SYSTEM_FONTS,
  SCALE_RATIO_VALUES,
} from "../../types";

export function buildTypographyExport(state: TypographyState): {
  content: string;
  filename: string;
} {
  const format = state.downloadFormat;
  const name = state.downloadName || "typography";

  switch (format) {
    case "css-vars":
      return {
        content: generateCSSVariables(state),
        filename: `${name}.css`,
      };
    case "tailwind":
      return {
        content: generateTailwindConfig(state),
        filename: `${name}.tailwind.js`,
      };
    case "react":
    default:
      return {
        content: generateReactComponent(state),
        filename: `${name}.tsx`,
      };
  }
}

function generateCSSVariables(state: TypographyState): string {
  const fontFamily =
    state.fontBucket === "google"
      ? `"${state.googleFontFamily}", sans-serif`
      : SYSTEM_FONTS[state.systemFontIdx]?.css || "system-ui, sans-serif";

  const ratio = SCALE_RATIO_VALUES[state.scaleRatio];
  const fluid = state.fluidMode;

  let css = `/* Typography System - Generated by UI Foundry */

:root {
  /* Base */
  --font-family: ${fontFamily};
  --font-size-base: ${state.baseSize}${state.baseSizeUnit};
  --line-height-base: ${state.defaultLineHeight};
  --letter-spacing-base: ${state.defaultLetterSpacing}${state.defaultLetterSpacingUnit};
  --word-spacing-base: ${state.defaultWordSpacing}${state.defaultWordSpacingUnit};

  /* Headings */
`;

  state.headings.forEach((h) => {
    if (fluid) {
      const min = h.fontSize * 0.8;
      const max = h.fontSize * 1.2;
      css += `  --font-size-h${h.level}: clamp(${min}${h.fontSizeUnit}, ${h.fontSize}${h.fontSizeUnit} + 1vw, ${max}${h.fontSizeUnit});\n`;
    } else {
      css += `  --font-size-h${h.level}: ${h.fontSize}${h.fontSizeUnit};\n`;
    }
    css += `  --font-weight-h${h.level}: ${h.fontWeight};\n`;
    css += `  --line-height-h${h.level}: ${h.lineHeight};\n`;
    css += `  --letter-spacing-h${h.level}: ${h.letterSpacing}${h.letterSpacingUnit};\n`;
  });

  css += `
  /* Body Styles */
  --font-size-body: ${state.body.fontSize}${state.body.fontSizeUnit};
  --font-weight-body: ${state.body.fontWeight};
  --line-height-body: ${state.body.lineHeight};

  --font-size-lead: ${state.lead.fontSize}${state.lead.fontSizeUnit};
  --font-weight-lead: ${state.lead.fontWeight};
  --line-height-lead: ${state.lead.lineHeight};

  --font-size-small: ${state.small.fontSize}${state.small.fontSizeUnit};
  --font-weight-small: ${state.small.fontWeight};
  --line-height-small: ${state.small.lineHeight};

  --font-size-caption: ${state.caption.fontSize}${state.caption.fontSizeUnit};
  --font-weight-caption: ${state.caption.fontWeight};
  --line-height-caption: ${state.caption.lineHeight};
}

/* Utility Classes */
.text-h1 { font-size: var(--font-size-h1); font-weight: var(--font-weight-h1); line-height: var(--line-height-h1); letter-spacing: var(--letter-spacing-h1); }
.text-h2 { font-size: var(--font-size-h2); font-weight: var(--font-weight-h2); line-height: var(--line-height-h2); letter-spacing: var(--letter-spacing-h2); }
.text-h3 { font-size: var(--font-size-h3); font-weight: var(--font-weight-h3); line-height: var(--line-height-h3); letter-spacing: var(--letter-spacing-h3); }
.text-h4 { font-size: var(--font-size-h4); font-weight: var(--font-weight-h4); line-height: var(--line-height-h4); letter-spacing: var(--letter-spacing-h4); }
.text-h5 { font-size: var(--font-size-h5); font-weight: var(--font-weight-h5); line-height: var(--line-height-h5); letter-spacing: var(--letter-spacing-h5); }
.text-h6 { font-size: var(--font-size-h6); font-weight: var(--font-weight-h6); line-height: var(--line-height-h6); letter-spacing: var(--letter-spacing-h6); }

.text-body { font-size: var(--font-size-body); font-weight: var(--font-weight-body); line-height: var(--line-height-body); }
.text-lead { font-size: var(--font-size-lead); font-weight: var(--font-weight-lead); line-height: var(--line-height-lead); }
.text-small { font-size: var(--font-size-small); font-weight: var(--font-weight-small); line-height: var(--line-height-small); }
.text-caption { font-size: var(--font-size-caption); font-weight: var(--font-weight-caption); line-height: var(--line-height-caption); }
`;

  return css;
}

function generateTailwindConfig(state: TypographyState): string {
  const fontFamily =
    state.fontBucket === "google"
      ? `["${state.googleFontFamily}", "sans-serif"]`
      : `[${SYSTEM_FONTS[state.systemFontIdx]?.css
          .split(",")
          .map((f) => `"${f.trim().replace(/['"]/g, "")}"`)
          .join(", ")}]`;

  let config = `// Tailwind Typography Config - Generated by UI Foundry

module.exports = {
  theme: {
    extend: {
      fontFamily: {
        sans: ${fontFamily},
      },
      fontSize: {
`;

  state.headings.forEach((h) => {
    config += `        'h${h.level}': ['${h.fontSize}${h.fontSizeUnit}', { lineHeight: '${h.lineHeight}', letterSpacing: '${h.letterSpacing}${h.letterSpacingUnit}', fontWeight: '${h.fontWeight}' }],\n`;
  });

  config += `        'body': ['${state.body.fontSize}${state.body.fontSizeUnit}', { lineHeight: '${state.body.lineHeight}', fontWeight: '${state.body.fontWeight}' }],
        'lead': ['${state.lead.fontSize}${state.lead.fontSizeUnit}', { lineHeight: '${state.lead.lineHeight}', fontWeight: '${state.lead.fontWeight}' }],
        'small': ['${state.small.fontSize}${state.small.fontSizeUnit}', { lineHeight: '${state.small.lineHeight}', fontWeight: '${state.small.fontWeight}' }],
        'caption': ['${state.caption.fontSize}${state.caption.fontSizeUnit}', { lineHeight: '${state.caption.lineHeight}', fontWeight: '${state.caption.fontWeight}' }],
      },
    },
  },
};
`;

  return config;
}

function generateReactComponent(state: TypographyState): string {
  const fontFamily =
    state.fontBucket === "google"
      ? `"${state.googleFontFamily}", sans-serif`
      : SYSTEM_FONTS[state.systemFontIdx]?.css || "system-ui, sans-serif";

  return `// Typography Component - Generated by UI Foundry
import React from "react";

type TypographyVariant = "h1" | "h2" | "h3" | "h4" | "h5" | "h6" | "body" | "lead" | "small" | "caption";

interface TypographyProps {
  variant?: TypographyVariant;
  children: React.ReactNode;
  as?: keyof JSX.IntrinsicElements;
  className?: string;
  style?: React.CSSProperties;
}

const variantStyles: Record<TypographyVariant, React.CSSProperties> = {
${state.headings
  .map(
    (h) => `  h${h.level}: {
    fontSize: "${h.fontSize}${h.fontSizeUnit}",
    fontWeight: ${h.fontWeight},
    lineHeight: ${h.lineHeight},
    letterSpacing: "${h.letterSpacing}${h.letterSpacingUnit}",
    textTransform: "${h.textTransform}",
  },`,
  )
  .join("\n")}
  body: {
    fontSize: "${state.body.fontSize}${state.body.fontSizeUnit}",
    fontWeight: ${state.body.fontWeight},
    lineHeight: ${state.body.lineHeight},
  },
  lead: {
    fontSize: "${state.lead.fontSize}${state.lead.fontSizeUnit}",
    fontWeight: ${state.lead.fontWeight},
    lineHeight: ${state.lead.lineHeight},
  },
  small: {
    fontSize: "${state.small.fontSize}${state.small.fontSizeUnit}",
    fontWeight: ${state.small.fontWeight},
    lineHeight: ${state.small.lineHeight},
  },
  caption: {
    fontSize: "${state.caption.fontSize}${state.caption.fontSizeUnit}",
    fontWeight: ${state.caption.fontWeight},
    lineHeight: ${state.caption.lineHeight},
  },
};

const variantElements: Record<TypographyVariant, keyof JSX.IntrinsicElements> = {
  h1: "h1",
  h2: "h2",
  h3: "h3",
  h4: "h4",
  h5: "h5",
  h6: "h6",
  body: "p",
  lead: "p",
  small: "span",
  caption: "span",
};

export function Typography({
  variant = "body",
  children,
  as,
  className,
  style,
}: TypographyProps) {
  const Component = as || variantElements[variant];
  const baseStyle: React.CSSProperties = {
    fontFamily: "${fontFamily}",
    ...variantStyles[variant],
    ...style,
  };

  return (
    <Component className={className} style={baseStyle}>
      {children}
    </Component>
  );
}

export default Typography;
`;
}
